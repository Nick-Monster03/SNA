"""
02_verify_data.py - Runs data validation and threshold checks prior to network analysis (Phase 2).

Run AFTER 01_build_networks.py, from the project root directory:
    python src/02_verify_data.py

Reads:
  04_data/networks/yearly/                      yearly networks generated by 01_build_networks.py
  04_data/networks/periods/                     period networks generated by 01_build_networks.py
  04_data/networks/metadata/regions.csv         node list generated by 01_build_networks.py
  04_data/external/NUTS_RG_20M_2016_4326.geojson  region boundaries and names (GISCO)
  04_data/external/Eurostat_PIL_NUTS2.csv         regional GDP per capita (Eurostat) - optional

Outputs (saved in 04_data/networks/logs/):
  threshold_checks.csv   sensitivity table across edge weight thresholds
  checks_report.txt      full text log of all verification checks (for the report Data section)
"""

import json
from pathlib import Path

import networkx as nx
import pandas as pd

# =============================================================================
# CONFIGURATION
# =============================================================================
NETWORKS_DIR = Path("04_data/networks")
YEARLY_DIR = NETWORKS_DIR / "yearly"
PERIODS_DIR = NETWORKS_DIR / "periods"
METADATA_DIR = NETWORKS_DIR / "metadata"
LOGS_DIR = NETWORKS_DIR / "logs"

EXTERNAL_DIR = Path("04_data/external")
BOUNDARIES_FILE = EXTERNAL_DIR / "NUTS_RG_20M_2016_4326.geojson"
GDP_FILE = EXTERNAL_DIR / "Eurostat_PIL_NUTS2.csv"

PERIODS = {
    "pre_covid": (2018, 2019),
    "covid": (2020, 2021),
    "post_covid": (2022, 2023),
}
THRESHOLDS = [1, 2, 3, 5, 10, 20]  # minimum students/year to keep a binary edge
# =============================================================================

log_lines = []


def write_log(text=""):
    print(text)
    log_lines.append(str(text))


def load_network(name):
    """Loads a network: either a year (e.g., 2019) or a period (e.g., 'pre_covid')."""
    if isinstance(name, int) or str(name).isdigit():
        return pd.read_csv(YEARLY_DIR / f"network_{name}.csv")
    return pd.read_csv(PERIODS_DIR / f"network_{name}.csv")


# -----------------------------------------------------------------------------
def check_united_kingdom():
    write_log("=" * 78)
    write_log("CHECK: how United Kingdom student flows change over time (Brexit case)")
    write_log("=" * 78)
    years = sorted(int(p.stem.split("_")[1]) for p in YEARLY_DIR.glob("network_20*.csv"))
    rows = []
    for y in years:
        net = load_network(y)
        uk_out = net[net.origin.str.startswith("UK")]
        uk_in = net[net.destination.str.startswith("UK")]
        total = net.students.sum()
        rows.append(
            {
                "year": y,
                "UK_outgoing": int(uk_out.students.sum()),
                "UK_incoming": int(uk_in.students.sum()),
                "UK_share_of_total_%": round(100 * (uk_out.students.sum() + uk_in.students.sum()) / total, 1),
                "UK_active_regions": len(set(uk_out.origin) | set(uk_in.destination)),
            }
        )
    write_log(pd.DataFrame(rows).to_string(index=False))
    write_log()


def check_thresholds():
    write_log("=" * 78)
    write_log("CHECK: which edge weight threshold to use for the binary networks")
    write_log("Period networks: an edge is kept only if it has at least N students/year on average.")
    write_log("=" * 78)
    n_regions = len(pd.read_csv(METADATA_DIR / "regions.csv"))
    rows = []
    for name in PERIODS:
        net = load_network(name)
        for t in THRESHOLDS:
            sel = net[net.students >= t]
            G = nx.from_pandas_edgelist(sel, "origin", "destination", create_using=nx.DiGraph)
            n = G.number_of_nodes()
            wcc = max((len(c) for c in nx.weakly_connected_components(G)), default=0)
            scc = max((len(c) for c in nx.strongly_connected_components(G)), default=0)
            rows.append(
                {
                    "network": name,
                    "threshold": t,
                    "regions_with_edges": n,
                    "edges": G.number_of_edges(),
                    "density": round(nx.density(G), 4) if n > 1 else 0,
                    "students_kept_%": round(100 * sel.students.sum() / net.students.sum(), 1),
                    "regions_in_giant_wcc_%": round(100 * wcc / n_regions, 1),
                    "regions_in_giant_scc_%": round(100 * scc / n_regions, 1),
                }
            )
    table = pd.DataFrame(rows)
    write_log(table.to_string(index=False))
    LOGS_DIR.mkdir(parents=True, exist_ok=True)
    table.to_csv(LOGS_DIR / "threshold_checks.csv", index=False)
    write_log(
        f"\n(percentages computed over all {n_regions} regions; table saved to {LOGS_DIR}/threshold_checks.csv)"
    )
    write_log()


def region_names():
    g = json.loads(BOUNDARIES_FILE.read_text(encoding="utf-8"))
    return {
        f["properties"]["NUTS_ID"]: f["properties"]["NAME_LATN"]
        for f in g["features"]
        if f["properties"]["LEVL_CODE"] == 2
    }


def check_boundaries():
    write_log("=" * 78)
    write_log(f"CHECK: are all network regions present in the boundary file ({BOUNDARIES_FILE.name})?")
    write_log("=" * 78)
    if not BOUNDARIES_FILE.exists():
        write_log(f"File {BOUNDARIES_FILE} not found: check skipped.\n")
        return
    names = region_names()
    reg = pd.read_csv(METADATA_DIR / "regions.csv")
    missing = []
    for code in reg.region:
        parts = code.split("+")  # merged regions (e.g., NO01+NO03...) are checked piece by piece
        if not all(p in names for p in parts):
            missing.append(code)
    write_log(
        f"Network regions: {len(reg)} - matched: {len(reg) - len(missing)} - missing: {missing or 'none'}"
    )
    write_log("(merged regions created by 01_build_networks.py are checked piece by piece)\n")


def check_gdp():
    write_log("=" * 78)
    write_log(f"CHECK: does every network region have GDP data ({GDP_FILE.name})?")
    write_log("=" * 78)
    if not GDP_FILE.exists():
        write_log(f"File {GDP_FILE} not found: check skipped.\n")
        return
    gdp = pd.read_csv(GDP_FILE)
    gdp.columns = [c.strip() for c in gdp.columns]
    if "unit" in gdp.columns:
        write_log(f"Units available in GDP file: {sorted(gdp['unit'].unique())}")
        gdp = gdp[gdp["unit"] == "EUR_HAB"]
    gdp = gdp[gdp["geo"].astype(str).str.len() == 4]  # NUTS 2 regions only
    reg = pd.read_csv(METADATA_DIR / "regions.csv")
    for name, (a, b) in PERIODS.items():
        # A region has period GDP if a valid value exists for every year in the period
        present = None
        for year in range(a, b + 1):
            year_ok = set(gdp.loc[(gdp["TIME_PERIOD"] == year) & gdp["OBS_VALUE"].notna(), "geo"])
            present = year_ok if present is None else present & year_ok
        missing = [c for c in reg.region if not all(p in present for p in c.split("+"))]
        write_log(f"{name} ({a}-{b}): regions missing GDP {len(missing)} out of {len(reg)}")
        by_country = pd.Series([m[:2] for m in missing]).value_counts()
        if len(by_country):
            write_log("      by country: " + ", ".join(f"{c} {n}" for c, n in by_country.items()))
            if len(missing) <= 40:
                write_log("      " + ", ".join(missing))
    write_log()


if __name__ == "__main__":
    LOGS_DIR.mkdir(parents=True, exist_ok=True)
    check_united_kingdom()
    check_thresholds()
    check_boundaries()
    check_gdp()
    (LOGS_DIR / "checks_report.txt").write_text("\n".join(log_lines) + "\n", encoding="utf-8")
    print(f"Results saved to {LOGS_DIR}/checks_report.txt")